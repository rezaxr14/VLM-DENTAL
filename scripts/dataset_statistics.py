#!/usr/bin/env python3
"""Dataset statistics computed from the trace files that exist NOW (not copied from older documents).

    python scripts/dataset_statistics.py --traces-dir data/traces --dev-split data/splits/dentex_dev.json --output docs/DATASET_STATISTICS.md

Per ``train_cot_traces*.jsonl`` (verified traces; the ``*unverified*`` file is skipped): traces, unique ``(dataset, image_id)``
images, duplicated keys, ground-truth findings (total, per image, by diagnosis), healthy images (ground truth ``[]``), how many
images fall in the dev split, and the with-tools / no-tools parity of each pair. Read-only apart from ``--output``.
"""

from __future__ import annotations

import argparse
import json
import sys
from collections import Counter
from pathlib import Path

REPO_ROOT = Path(__file__).resolve().parent.parent
if str(REPO_ROOT) not in sys.path:
    sys.path.insert(0, str(REPO_ROOT))

from dental_agent.data.dev_split import image_key, load_dev_keys  # noqa: E402


def read_traces(path: Path) -> list[dict]:
    rows = []
    with open(path, "r", encoding="utf-8") as fh:
        for line in fh:
            if line.strip():
                rows.append(json.loads(line))
    return rows


def _infer_dataset(rec: dict, path: Path) -> str:
    return str(rec.get("dataset") or ("tufts" if "tufts" in path.name.lower() else "dentex")).lower()


def file_stats(path: Path, dev_keys: set[str]) -> dict:
    rows = read_traces(path)
    keys = [image_key(_infer_dataset(r, path), r.get("image_id")) for r in rows]
    key_count = Counter(keys)
    per_image: dict[str, list] = {}
    for k, r in zip(keys, rows):
        per_image.setdefault(k, r.get("ground_truth") or [])
    n_find = [len(g) for g in per_image.values()]
    diag = Counter(str(f.get("diagnosis") or f.get("pathology") or "unknown").lower() for g in per_image.values() for f in g)
    return {
        "file": path.name,
        "traces": len(rows),
        "images": len(per_image),
        "duplicate_keys": sorted(k for k, c in key_count.items() if c > 1),
        "findings": sum(n_find),
        "healthy": sum(1 for n in n_find if n == 0),
        "findings_per_image": dict(sorted(Counter(min(n, 7) for n in n_find).items())),
        "by_diagnosis": dict(sorted(diag.items())),
        "in_dev_split": sum(1 for k in per_image if k in dev_keys),
        "keys": set(per_image),
    }


def collect(traces_dir: Path, dev_keys: set[str]) -> list[dict]:
    files = sorted(p for p in traces_dir.glob("train_cot_traces*.jsonl") if "unverified" not in p.name)
    return [file_stats(p, dev_keys) for p in files]


def parity(stats: list[dict]) -> list[dict]:
    by_name = {s["file"]: s for s in stats}
    out = []
    for name, s in by_name.items():
        if name.endswith("_no_tools.jsonl"):
            continue
        twin = by_name.get(name.replace(".jsonl", "_no_tools.jsonl"))
        if twin is None:
            continue
        out.append({"file": name, "with_tools": len(s["keys"]), "no_tools": len(twin["keys"]),
                    "only_with_tools": sorted(s["keys"] - twin["keys"]), "only_no_tools": sorted(twin["keys"] - s["keys"])})
    return out


def render(stats: list[dict], par: list[dict], dev_path: str | None) -> str:
    L = ["# Dataset statistics (generated)", "",
         "Generated by `python scripts/dataset_statistics.py` from the trace files present when it ran. Do not edit by hand; counts in older",
         "documents (`COT_RESULTS.md`, `PAPER_MILESTONES.md`, `SFT_CONFIG.md`) predate the patch-0028 regeneration and are superseded by this file.",
         f"Dev split: `{dev_path}`." if dev_path else "Dev split: none given (in-dev counts are 0).", "",
         "| File | Traces | Images | Findings | Healthy | In dev split | Duplicate keys |",
         "| :--- | ---: | ---: | ---: | ---: | ---: | ---: |"]
    for s in stats:
        L.append(f"| `{s['file']}` | {s['traces']} | {s['images']} | {s['findings']} | {s['healthy']} | {s['in_dev_split']} | {len(s['duplicate_keys'])} |")
    L += ["", "## Findings per image (7 = 7 or more)", "", "| File | " + " | ".join(str(i) for i in range(0, 8)) + " |",
          "| :--- | " + " | ".join("---:" for _ in range(8)) + " |"]
    for s in stats:
        L.append(f"| `{s['file']}` | " + " | ".join(str(s["findings_per_image"].get(i, 0)) for i in range(0, 8)) + " |")
    diags = sorted({d for s in stats for d in s["by_diagnosis"]})
    if diags:
        L += ["", "## Findings by diagnosis", "", "| File | " + " | ".join(diags) + " |", "| :--- | " + " | ".join("---:" for _ in diags) + " |"]
        for s in stats:
            L.append(f"| `{s['file']}` | " + " | ".join(str(s["by_diagnosis"].get(d, 0)) for d in diags) + " |")
    L += ["", "## With-tools / no-tools parity", ""]
    if not par:
        L.append("No with-tools / no-tools file pair found.")
    for p in par:
        gap = f"; only with tools: {', '.join(p['only_with_tools'])}" if p["only_with_tools"] else ""
        gap += f"; only no tools: {', '.join(p['only_no_tools'])}" if p["only_no_tools"] else ""
        L.append(f"* `{p['file']}`: {p['with_tools']} images with tools, {p['no_tools']} without{gap or ' (identical image sets)'}")
    dup = [s for s in stats if s["duplicate_keys"]]
    if dup:
        L += ["", "## Duplicate image keys (more than one trace for the same image)", ""]
        L += [f"* `{s['file']}`: {', '.join(s['duplicate_keys'][:20])}" for s in dup]
    return "\n".join(L) + "\n"


def main() -> None:
    ap = argparse.ArgumentParser(description=__doc__.split("\n")[0])
    ap.add_argument("--traces-dir", default="data/traces")
    ap.add_argument("--dev-split", default=None, help="data/splits/dentex_dev.json (optional)")
    ap.add_argument("--output", default="docs/DATASET_STATISTICS.md")
    args = ap.parse_args()

    traces_dir = Path(args.traces_dir)
    if not traces_dir.is_dir():
        traces_dir = REPO_ROOT / args.traces_dir
    stats = collect(traces_dir, load_dev_keys(args.dev_split) if args.dev_split else set())
    if not stats:
        raise SystemExit(f"[INPUT NOT FOUND] no train_cot_traces*.jsonl in {traces_dir}. Fix: python scripts/sync_traces_hf.py --download")
    text = render(stats, parity(stats), args.dev_split)
    out = Path(args.output)
    out.parent.mkdir(parents=True, exist_ok=True)
    out.write_text(text, encoding="utf-8")
    print(text)
    print(f"[STATS] written to {out}")


if __name__ == "__main__":
    main()
